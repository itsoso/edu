def seed():
    init_db()
    with db() as conn:
        # 清空历史 seed 数据, 保持幂等
        conn.execute("DELETE FROM scores")
        conn.execute("DELETE FROM exams")
        conn.execute("DELETE FROM tasks")

        for (order, stage, name, date, kxue, eng, math, yuwen, shehui,
             total, class_rank, grade_rank, notes) in EXAMS:
            cur = conn.execute(
                """INSERT INTO exams
                   (exam_name, exam_date, stage, total, class_rank, grade_rank, notes, sort_order)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (name, date, stage, total, class_rank, grade_rank, notes, order),
            )
            exam_id = cur.lastrowid
            subject_scores = {
                "科学": kxue, "英语": eng, "数学": math,
                "语文": yuwen, "社会": shehui,
            }
            for subject, score in subject_scores.items():
                if score is not None:
                    conn.execute(
                        "INSERT INTO scores (exam_id, subject, score, full_mark) VALUES (?, ?, ?, ?)",
                        (exam_id, subject, score, FULL_MARKS[subject]),
                    )

        # Tasks
        for (week, dow, subject, title, desc, minutes) in PLAN_TASKS:
            conn.execute(
                """INSERT INTO tasks (week, day_of_week, subject, title, description, minutes)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (week, dow, subject, title, desc, minutes),
            )

    print(f"Seeded {len(EXAMS)} exams and {len(PLAN_TASKS)} plan tasks.")


if __name__ == "__main__":
    seed()
